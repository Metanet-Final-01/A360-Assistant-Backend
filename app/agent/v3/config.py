import os
from pathlib import Path

# 프로젝트 루트의 .env를 있으면 로드 (python-dotenv 없거나 파일 없으면 조용히 통과)
try:
    from dotenv import load_dotenv

    # parents[3] = 리포 루트 (이 파일은 app/agent/v2/config.py — 버전 폴더로 한 단계 깊다).
    load_dotenv(Path(__file__).resolve().parents[3] / ".env")
except ImportError:
    pass

OPENAI_API_KEY = os.getenv("OPENAI_API_KEY", "")
# 기본은 가벼운 모델. 교체는 코드 수정 없이 .env의 OPENAI_MODEL로 한다.
OPENAI_MODEL = os.getenv("OPENAI_MODEL", "gpt-5.4-mini")

# 그래프 전체 동시 LLM 호출 상한 (rate limit 방어). orchestrator와 recommend 서브그래프가
# 공유한다 — 값이 갈리면 중첩 실행(orchestrator→recommend)의 동시성 예산이 어긋나므로
# 한 곳에서 관리한다. 배포 환경별 rate limit에 맞춰 .env로 조정 가능(다른 설정과 일관).
MAX_LLM_CONCURRENCY = int(os.getenv("MAX_LLM_CONCURRENCY", "3"))

# compose 한 호출의 출력 토큰 상한. 흐름도 JSON은 액션·파라미터·rationale이 쌓여 길어지는데
# 미지정이면 provider 기본 천장(실측 정황상 4096)에 걸려 JSON이 중간에서 잘린다 —
# 2026-07-28 실측에서 후보 3개가 모두 8.7k~13k자에서 절단돼 한 턴이 통째로 실패했다.
# 천장을 명시해 올린다. 0으로 두면 미지정(현행 provider 기본값)으로 돌아간다 — 모델이
# 이 값을 거부하는 경우의 탈출구다.
#
# ⚠ **COMPOSE_REASONING과 한 쌍이다.** 이 값은 completion 전체(추론 토큰 + 본문)를 센다.
# 실측(2026-07-29): 상한 16,000에 medium 추론을 켜니 `reasoning_tokens=16000`으로 예산을
# 전부 먹고 본문을 한 글자도 못 냈다 — 절단을 막으려고 올려 둔 값이 절단을 일으켰다.
# 추론을 켤 때는 **추론 몫 + 본문 몫**을 함께 담을 수 있게 올려야 한다(본문은 실측 2~2.6k).
# 추론을 끄면 16,000으로 되돌려도 충분하다 — 남는 상한은 비용이 아니라 여유일 뿐이다.
COMPOSE_MAX_TOKENS = int(os.getenv("COMPOSE_MAX_TOKENS", "32000"))

# compose 출력에 JSON mode를 걸지 여부(0이면 끈다).
#
# v3의 다른 구조화 출력은 전부 `jsonio.chat_json` → `response_format={"type":"json_object"}`을
# 거치는데(spec_builder·semantic·judge·surgeon·cards) **compose만 raw ChatOpenAI라 문법
# 보장을 못 받고 있었다.** 가장 길고 중첩이 깊은 출력이 하필 무보장이었던 셈이다.
# 실측(2026-07-28): 후보 파싱 실패 9건이 전부 '텍스트는 }로 끝나는데 중간 문법이 깨짐'
# 유형이었다(절단 아님 — 출력 2.5k~4k 토큰으로 상한 16k의 1/4). JSON mode는 이 유형을
# 공급자 수준에서 없앤다.
#
# ⚠ JSON mode는 메시지에 'json' 문자열이 있어야 한다(OpenAI 제약) — compose_agent.md의
# 출력 지시가 "JSON 객체 하나만"이라 충족한다. 툴 바인딩과 함께 쓸 때 공급자가 거부하면
# 이 값을 0으로 두고 되돌린다.
COMPOSE_JSON_MODE = int(os.getenv("COMPOSE_JSON_MODE", "1"))

# spec_builder가 analyze의 분해 결과를 입력으로 받을지 (0이면 원문만 본다) — A/B 측정용.
#
# 왜 재는가: analyze의 산출물은 사용자용 분석 화면·근거 추적(page·snippet)에는 쓰이지만,
# **흐름도 경로에는 얇게 전달된다** — `analysis_brief`가 요약 한 줄 + 단계 이름·설명·시스템 +
# 미확정 목록만 넘기고 inputs·outputs·branching·evidence는 버린다. 게다가 spec_builder는
# 원문도 함께 받는다. 그래서 "이미 원문을 보는데 요약 7줄이 뭘 더하나"가 성립한다.
#
# 반대로 끄면 한 호출이 **읽기 + 분해 + 정형화**를 다 하게 되는데, 이건 compose를 구조/값으로
# 쪼갠 것과 같은 모양이다(실측 2026-07-29: 쪼개니 구조 위반 가중 481 → 14). 스펙은 조사 질의·
# 커버리지 분모·구조 단계 목표가 전부 타는 기반이라, 여기서 힘이 빠지면 아래가 다 내려간다.
#
# 어느 쪽인지는 추측이 아니라 같은 문서로 한 턴씩 돌려 비교한다. 볼 것: must 개수와 문장 품질,
# 조사 질의의 동작 단위, must_coverage, 최종 위반·신뢰도.
#
# 1차 실측(2026-07-29, 원문만): must 7 → 5로 뭉쳤다("접속 + 증권 클릭"이 한 요구, "엑셀 입력 +
# 테두리"가 한 요구). must_coverage는 0.67 → 0.66으로 사실상 같았지만 **분모가 달라** 같은
# 비율이 같은 품질을 뜻하지 않는다 — 요구를 굵게 잡으면 커버하기도 쉬워진다. 같은 턴에 surgeon
# 프롬프트 수정과 게이트 partial 지적이 함께 들어가 변수가 셋이라, 분석 유무만 갈린 비교가
# 아니었다. 다른 코드를 고정한 채 1로 한 턴 더 돌려 짝을 맞춘다.
SPEC_USE_ANALYSIS = int(os.getenv("SPEC_USE_ANALYSIS", "1"))

# 구조 단계(흐름도 초안)에만 거는 추론 강도. "" 또는 인정 목록 밖의 값이면 인자를 안 보낸다
# (= 공급자 기본값). 값: none · low · medium · high · xhigh.
#
# 왜 구조 단계만인가: 여기가 흐름도의 배치를 정하는 **유일한** 자리다. 이후 단계는 고치거나
# 채울 뿐이다. 그리고 반복해 틀린 것들 — Try 경계, 세션 여닫는 순서, step 배치 — 이 전부
# 지식이 아니라 **계획**의 문제였다(액션은 다 알고 있는데 어디에 둘지에서 틀렸다).
# 값 채우기는 파라미터만 채우는 단순 작업인 데다 step별 병렬이라 켜면 비용이 가장 크게 붙는다.
#
# ⚠ 추론 토큰은 **출력으로 과금**되고 COMPOSE_MAX_TOKENS 상한도 함께 먹는다 — 강도를 올릴수록
# 비용이 오르고, 너무 길면 본문 JSON이 잘린다. 비호환이면 `_ask`가 추론을 먼저 떼고 재시도한다.
# 실측(2026-07-29) 같은 문서로 강도별 2턴씩:
#
#            게이트   신뢰도   구조 두 호출        턴 비용
#   medium    2건     0.31    10.8k+10.3k out    $0.1748
#   medium    3건     0.15    15.9k+19.2k out    $0.2584   ← 233초
#   low       0건     0.47     3.0k+ 3.3k out    $0.1012
#   low       4건     0.20     3.3k+ 3.5k out    $0.1163
#
# **강도를 올려도 편차가 줄지 않았다** — medium도 게이트 2↔3, 신뢰도 0.31↔0.15로 흔들린다.
# 대신 2.2배 비싸고 5배 느리며, 추론 소비량 자체가 불안정하다(10.3k → 19.2k). 두 medium 턴
# 모두 테두리 서식 요구를 놓쳤고 두 low 턴은 담았다. 그래서 low로 확정한다.
#
# ⚠ 이 A/B는 애초에 깨끗하지 않았다: 같은 문서인데 **스펙이 턴마다 달랐다**(총요구 8→9→10→11,
# 오류 정책이 "안전 종료"에서 "제한 재시도"로). compose 입력이 흔들리므로 compose 강도만
# 재려면 스펙을 고정해야 한다 — 편차의 출처는 여기부터 봐야 한다.
#
# ⚠ 이 값은 **여기서만** 바뀐다. 로컬 컨테이너는 app/ 디렉터리만 마운트하고 .env는 생성
# 시점에 주입되므로, .env에 써 넣고 restart하면 조용히 무시된다(실측). 강도를 바꾸려면
# 이 기본값을 고치고 `docker restart a360-backend`.
COMPOSE_REASONING = os.getenv("COMPOSE_REASONING", "low").strip().lower()

# 값 채우기 한 호출이 맡는 액션 수 상한. 이 수를 넘으면 흐름도를 subtree 단위로 잘라
# 여러 호출에 나눠 맡긴다(호출들은 시스템 프롬프트가 같아 캐시를 타고 병렬로 돈다).
#
# 왜 필요한가: 값 단계는 액션마다 파라미터를 여러 개씩 내는 일이라 출력이 액션 수에
# 비례해 길어지고, 길어지면 **뒤쪽 액션이 빈 채로 나온다** — 구조/값을 쪼갠 이유와
# 같은 실패가 값 단계 안에서 다시 일어난다. 실측(2026-07-29): 액션 19개를 한 호출로
# 맡겼더니 Try 안쪽까지는 다 찼는데 그 뒤 Catch·Finally 4개가 파라미터 0개로 나와
# 세션 닫기 액션 셋이 전부 R3(필수 파라미터 없음)로 걸렸다.
#
# 앞서 있던 분할은 step 단위였는데, 구조 프롬프트가 "업무가 길어도 step은 늘리지
# 않는다"를 못 박은 뒤로 step이 늘 1개가 되어 **분할 자체가 발동하지 않았다.**
# 그래서 단위를 step이 아니라 subtree로 바꿨다 — 컨테이너 하나가 상한을 넘으면
# 그 컨테이너를 떼고 자식들을 다시 잰다.
#
# 크게 두면(예: 999) 청크가 하나가 되어 분할 전 동작으로 돌아간다 — 탈출구다.
COMPOSE_FILL_CHUNK = int(os.getenv("COMPOSE_FILL_CHUNK", "8"))

# 구조 게이트가 "필수 요구가 빠졌다"고 판정했을 때 그 요구 문구로 카탈로그를 다시 조사해
# 구조를 한 번 더 만들지 여부 (0이면 끈다).
#
# 왜 켜는가: 커버리지 미달은 **수리로 풀리지 않는다.** 수리(surgeon)에게는 카탈로그를
# 검색할 수단이 없어서 아는 것 중에 고르게 되고, 그게 매번 빈 `Step`이다(실측 2026-07-29:
# `insert Step/Step`으로 답한 라운드들이 가중치를 0→20·0→30으로 올렸다). 조사를 가진
# 경로로 돌리면 실제로 액션을 찾아 넣는다 — 같은 세션에서 `Format cell`이 그렇게 들어왔다.
#
# ⚠ **켜면 턴당 LLM 2회가 늘어난다** (구조 재생성 1 + 커버리지 재측정 1, 실측 ~$0.03).
#
# ⚠⚠ **실측(2026-07-30) 첫 턴은 순손실이었다 — 그래서 기본을 0으로 둔다.** 조사는 제대로
# 돌아 요구 4건에 대한 액션을 찾았고(found=true) 액션이 14→17로 늘었는데, **재생성본이
# 닫힌 어휘 검증(2.5단)을 건너뛰어** `package="Recorder/Click"` ·
# `action="범용 레코더로 캡처한 객체에 대해 수행한"` 꼴의 오염이 R1 blocker 6건으로
# 게이트에 들어갔다: 게이트 7건 → 13건, 가중 910, 수리 4라운드를 태우고도 300.
# 최종 위반 3건 → 10건, 신뢰도 0.30 → 0.16, 턴 $0.0895 → $0.1274.
#
# 그 배선 결함은 고쳤다(재생성본도 `_fix_vocab`을 통과한다). 하지만 **고친 효과를 아직 안
# 쟀다.** 재기 전까지는 꺼 둔다 — 켜서 손해가 확인된 것을 기본으로 둘 수는 없다.
# 재측정 절차: 같은 문서로 0/1 한 턴씩, 스펙 지문(req_digest)이 같은지 먼저 확인하고
# `flow_confidence` · 게이트 커버리지 미달 건수 · R1 건수 · 턴 비용을 비교한다.
COMPOSE_COVERAGE_RETRY = int(os.getenv("COMPOSE_COVERAGE_RETRY", "0"))
